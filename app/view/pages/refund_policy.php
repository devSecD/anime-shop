<section class="policy-section">
  <h1>Política de reembolso</h1>
  <p>
    En <strong>Anime-Shop</strong> queremos que tengas la mejor experiencia de compra posible. 
    Si por alguna razón no estás completamente satisfecho con tu pedido, 
    ponemos a tu disposición nuestra política de devoluciones y reembolsos, 
    la cual está pensada para ser clara, justa y fácil de seguir.
  </p>

  <h2>Plazos para solicitar un reembolso</h2>
  <p>
    Puedes solicitar una devolución o reembolso dentro de los <strong>15 días naturales</strong> 
    posteriores a la fecha de recepción de tu pedido. Pasado este plazo, lamentablemente 
    no podremos procesar tu solicitud.
  </p>

  <h2>Productos elegibles</h2>
  <ul>
    <li>El producto debe estar en su <strong>empaque original</strong> y en perfectas condiciones.</li>
    <li>No deben haberse usado, lavado ni dañado los artículos.</li>
    <li>Los productos en oferta o de liquidación <strong>no son reembolsables</strong>, 
        salvo que lleguen defectuosos o dañados.</li>
    <li>Por motivos de higiene, ciertos artículos como ropa interior, 
        accesorios de uso personal o artículos de colección abiertos, 
        no son elegibles para devolución.</li>
  </ul>

  <h2>Procedimiento de devolución</h2>
  <ol>
    <li>Escríbenos a nuestro correo de soporte: 
        <a href="mailto:soporte@anime-shop.com">soporte@anime-shop.com</a> 
        indicando tu número de pedido y el motivo de la devolución.</li>
    <li>Te enviaremos las instrucciones para el envío de regreso del producto.</li>
    <li>Una vez recibido y revisado el artículo, te notificaremos la aprobación o rechazo 
        de tu solicitud de reembolso.</li>
  </ol>

  <h2>Reembolsos aprobados</h2>
  <p>
    Si tu devolución es aprobada, procesaremos tu reembolso dentro de los 
    <strong>7 a 10 días hábiles</strong>. El reembolso se realizará utilizando 
    el mismo método de pago que usaste para la compra.
  </p>

  <h2>Gastos de envío</h2>
  <p>
    Los costos de envío de la devolución corren por cuenta del cliente, 
    salvo en los casos donde el producto haya llegado defectuoso o incorrecto. 
    En ese caso, <strong>nosotros cubriremos los gastos</strong>.
  </p>

  <h2>Contacto</h2>
  <p>
    Si tienes dudas adicionales sobre nuestra política de reembolsos, 
    por favor contáctanos en 
    <a href="mailto:soporte@anime-shop.com">soporte@anime-shop.com</a>. 
    Estamos aquí para ayudarte en lo que necesites.
  </p>

  <p>
    Gracias por confiar en <strong>Anime-Shop</strong>. 
    Tu satisfacción es nuestra prioridad. ❤️
  </p>
